"""Regenerate the portfolio's SVG paths from public-domain Natural Earth data.

Run manually with Python 3; the website makes no external map requests.
The two orthographic insets have independent scales and share their projection
with the country boundaries and markers, so their locations stay aligned.
"""
import json
import math
from pathlib import Path
from urllib.request import urlopen

SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/'


def load(name):
    with urlopen(SOURCE + name + '.geojson', timeout=30) as response:
        return json.load(response)['features']


def project(point, center, origin, radius):
    lon, lat = map(math.radians, point)
    lon0, lat0 = map(math.radians, center)
    return [round(origin[0] + radius * math.cos(lat) * math.sin(lon - lon0), 2),
            round(origin[1] - radius * (math.cos(lat0) * math.sin(lat)
                  - math.sin(lat0) * math.cos(lat) * math.cos(lon - lon0)), 2)]


def simplify(points, tolerance=0.35):
    if len(points) < 3:
        return points
    a, b = points[0], points[-1]
    dx, dy = b[0] - a[0], b[1] - a[1]
    length = dx * dx + dy * dy
    distances = []
    for p in points[1:-1]:
        t = max(0, min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / length)) if length else 0
        distances.append(math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy))
    distance = max(distances)
    if distance <= tolerance:
        return [a, b]
    split = distances.index(distance) + 1
    return simplify(points[:split + 1], tolerance)[:-1] + simplify(points[split:], tolerance)


def path(features, projection):
    result = []
    for feature in features:
        geometry = feature['geometry']
        polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
        for polygon in polygons:
            for ring in polygon:
                points = simplify([project(p, **projection) for p in ring])
                if len(points) >= 4:
                    result.append('M' + 'L'.join(f'{x:g},{y:g}' for x, y in points) + 'Z')
    return ''.join(result)


regions = load('ne_110m_geography_regions_polys')
countries = load('ne_110m_admin_0_countries')
africa = dict(center=[18, 1], origin=[140, 160], radius=145)
europe = dict(center=[23, 54], origin=[360, 100], radius=240)
data = {
    'africa': path([f for f in regions if f['properties']['NAME'] in ['AFRICA', 'MADAGASCAR']], africa),
    'europe': path([f for f in regions if f['properties']['NAME'] in ['EUROPE', 'BRITISH ISLES', 'ICELAND']], europe),
    'nigeria': path([f for f in countries if f['properties']['ADMIN'] == 'Nigeria'], africa),
    'germany': path([f for f in countries if f['properties']['ADMIN'] == 'Germany'], europe),
    # Nigeria is represented by a country-level marker, not an asserted hometown.
    'nigeriaMarker': project([8.6753, 9.0820], **africa),
    'berlinMarker': project([13.4050, 52.5200], **europe),
}
target = Path(__file__).resolve().parents[1] / 'src/data/journey-map.js'
target.write_text('// Generated by scripts/generate-journey-map.py from Natural Earth (public domain).\n'
                  '// Orthographic geographic insets; each inset uses its own scale.\n'
                  + 'export const journeyMap = ' + json.dumps(data, indent=2) + ';\n')
print(f'Generated {target.name}: {target.stat().st_size} bytes')
